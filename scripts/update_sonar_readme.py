
from __future__ import annotations

import base64
import os
import re
import time
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.parse import urlencode
from urllib.request import Request, urlopen


PROJECT_ROOT = Path(__file__).resolve().parent.parent
README_PATH = PROJECT_ROOT / "README.md"
REPORT_TASK_PATH = PROJECT_ROOT / ".scannerwork" / "report-task.txt"

SONAR_HOST_URL = os.environ.get("SONAR_HOST_URL", "http://sonarqube:9000",).rstrip("/")
SONAR_TOKEN = os.environ.get("SONAR_TOKEN")
SONAR_PROJECT_KEY = os.environ.get("SONAR_PROJECT_KEY", "ukinory")

START_MARKER = "<!-- SONAR-METRICS:START -->"
END_MARKER = "<!-- SONAR-METRICS:END -->"

METRIC_KEYS = (
    "coverage",
    "bugs",
    "vulnerabilities",
    "code_smells",
    "duplicated_lines_density",
    "ncloc",
)


def sonar_get(endpoint: str, params: dict[str, str] | None = None) -> dict:
    """Make an authenticated request to the SonarQube Web API."""
    if not SONAR_TOKEN:
        raise RuntimeError(
            "SONAR_TOKEN is not set. Set the token in your terminal "
            "before running the analysis."
        )

    query = f"?{urlencode(params)}" if params else ""
    url = f"{SONAR_HOST_URL}{endpoint}{query}"

    credentials = base64.b64encode(f"{SONAR_TOKEN}:".encode()).decode()
    request = Request(
        url,
        headers={
            "Authorization": f"Basic {credentials}",
            "Accept": "application/json",
        },
    )

    try:
        with urlopen(request, timeout=30) as response:
            import json

            return json.loads(response.read().decode("utf-8"))
    except HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(
            f"SonarQube API returned HTTP {exc.code}: {detail}"
        ) from exc
    except URLError as exc:
        raise RuntimeError(
            f"Could not connect to SonarQube at {SONAR_HOST_URL}: {exc}"
        ) from exc


def read_ce_task_id() -> str:
    """Read the Compute Engine task ID generated by SonarScanner."""
    if not REPORT_TASK_PATH.is_file():
        raise FileNotFoundError(
            f"SonarScanner report not found at {REPORT_TASK_PATH}. "
            "Make sure the scanner writes .scannerwork into the repository root."
        )

    properties: dict[str, str] = {}

    for line in REPORT_TASK_PATH.read_text(encoding="utf-8").splitlines():
        if "=" in line:
            key, value = line.split("=", 1)
            properties[key.strip()] = value.strip()

    task_id = properties.get("ceTaskId")
    if not task_id:
        raise RuntimeError(
            f"No ceTaskId found in {REPORT_TASK_PATH}."
        )

    return task_id


def wait_for_analysis(task_id: str, timeout_seconds: int = 180) -> None:
    """Wait until SonarQube has processed the submitted analysis."""
    deadline = time.monotonic() + timeout_seconds

    while time.monotonic() < deadline:
        response = sonar_get(
            "/api/ce/task",
            {"id": task_id},
        )
        task = response.get("task", {})
        status = task.get("status")

        if status == "SUCCESS":
            print("SonarQube analysis processing completed.")
            return

        if status in {"FAILED", "CANCELED"}:
            raise RuntimeError(
                f"SonarQube analysis processing ended with status {status}."
            )

        print(f"Waiting for SonarQube analysis... ({status or 'PENDING'})")
        time.sleep(3)

    raise TimeoutError(
        f"SonarQube did not finish processing the analysis "
        f"within {timeout_seconds} seconds."
    )


def fetch_metrics() -> dict[str, str]:
    response = sonar_get(
        "/api/measures/component",
        {
            "component": SONAR_PROJECT_KEY,
            "metricKeys": ",".join(METRIC_KEYS),
        },
    )

    component = response.get("component", {})
    measures = component.get("measures", [])
    return {
        measure["metric"]: measure["value"]
        for measure in measures
        if "metric" in measure and "value" in measure
    }


def format_metric(metrics: dict[str, str], key: str) -> str:
    value = metrics.get(key)

    if value is None:
        return "N/A"

    if key in {"coverage", "duplicated_lines_density"}:
        return f"{float(value):.1f}%"

    if key in {"bugs", "vulnerabilities", "code_smells", "ncloc"}:
        return f"{int(float(value)):,}"

    return value


def build_readme_section(metrics: dict[str, str], quality_gate: str) -> str:
    rows = [
        ("Coverage", format_metric(metrics, "coverage")),
        ("Bugs", format_metric(metrics, "bugs")),
        ("Vulnerabilities", format_metric(metrics, "vulnerabilities")),
        ("Code smells", format_metric(metrics, "code_smells")),
        (
            "Duplicated lines",
            format_metric(metrics, "duplicated_lines_density"),
        ),
        ("Lines of code", format_metric(metrics, "ncloc")),
        ("Quality Gate", quality_gate),
    ]

    table = [
        START_MARKER,
        "| Metric | Value |",
        "|---|---:|",
    ]

    table.extend(f"| {name} | {value} |" for name, value in rows)
    table.append(END_MARKER)

    return "\n".join(table)


def update_readme(section: str) -> bool:
    """Replace the marked section, preserving the rest of the README."""
    if not README_PATH.is_file():
        raise FileNotFoundError(f"README not found: {README_PATH}")

    readme = README_PATH.read_text(encoding="utf-8")

    pattern = re.compile(
        re.escape(START_MARKER)
        + r".*?"
        + re.escape(END_MARKER),
        flags=re.DOTALL,
    )

    if not pattern.search(readme):
        raise RuntimeError(
            "Could not find the SonarQube markers in README.md. "
            f"Add {START_MARKER} and {END_MARKER} around the metrics table."
        )

    updated_readme = pattern.sub(lambda _: section, readme, count=1)

    if updated_readme == readme:
        print("README metrics are already up to date.")
        return False

    README_PATH.write_text(updated_readme, encoding="utf-8", newline="\n")
    print("README.md updated locally with the latest SonarQube metrics.")
    return True


def main() -> None:
    print(f"Retrieving SonarQube metrics for '{SONAR_PROJECT_KEY}'...")

    task_id = read_ce_task_id()
    wait_for_analysis(task_id)

    metrics = fetch_metrics()

    gate_response = sonar_get(
        "/api/qualitygates/project_status",
        {"projectKey": SONAR_PROJECT_KEY},
    )
    quality_gate = (
        gate_response.get("projectStatus", {}).get("status", "N/A")
    )

    section = build_readme_section(metrics, quality_gate)
    update_readme(section)


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, FileNotFoundError, TimeoutError, ValueError) as exc:
        raise SystemExit(f"Error updating SonarQube metrics: {exc}") from exc
